#!/usr/bin/env python3
# Generate exam-priority.ts — cluster-level star ratings per subject aspect.
# NON-DESTRUCTIVE: ratings only WEIGHT mock sampling (examSelect.ts); coverage
# floors keep every aspect in every paper, so a mis-rating is capped. No
# recurrence/exam-sitting data exists for any subject, so ratings rest on a
# STRUCTURAL PROXY — syllabus subtopic count (CPL) or question-bank volume
# (IR/GR/PPL) — and are labelled "limited evidence". Meteorology keeps its
# curated, cross-source-informed map. Regenerate: python3 scripts/gen-exam-priority.py
import re, subprocess, os
D = "src/app/data"

# ── Meteorology: curated (True North cross-source overlap + review). Kept verbatim.
MET = {
 "A.8.3":3,"A.8.4":3,"A.8.7":3,"A.8.8":3,"A.8.9":3,"A.8.10":3,"A.8.15":3,"A.8.17":3,"A.8.21":3,
 "A.8.1":2,"A.8.2":2,"A.8.5":2,"A.8.6":2,"A.8.11":2,"A.8.12":2,"A.8.13":2,"A.8.14":2,"A.8.16":2,"A.8.20":2,
 "A.8.18":1,"A.8.19":1,
}

def tier(sig):  # {code: signal} -> {code: star}; top third 3, bottom third 1, mid 2
    codes = sorted(sig, key=lambda c: (-sig[c], c))
    n = len(codes)
    if n == 0: return {}
    if n <= 2: return {c: 3 for c in codes}
    hi = max(1, round(n/3)); lo = max(1, n//3)
    out = {}
    for i, c in enumerate(codes):
        out[c] = 3 if i < hi else (1 if i >= n-lo else 2)
    return out

# ── Syllabus subtopic counts per aspect (centrality proxy for CPL subjects).
syl = open(f"{D}/sacaa-syllabus.ts").read().split("\n")
sub_counts = {}      # aspect code -> subtopic count
cur = None
for ln in syl:
    m = re.search(r'id:\s*"(A\.\d+\.\d+)"', ln)
    if m: cur = m.group(1); sub_counts.setdefault(cur, 0); continue
    if cur and re.search(r'id:\s*"A\.\d+\.\d+\.[a-z]+"', ln): sub_counts[cur] += 1

def by_prefix(pfx):  # subtopic counts for one subject's aspect prefix (e.g. "A.3")
    return {c: sub_counts[c] for c in sub_counts if c.startswith(pfx + ".")}

# ── Bank volume per sectionId (proxy for subjects with no syllabus subtopics).
def volume(files):
    vol = {}
    for f in files:
        p = f"{D}/{f}"
        if not os.path.exists(p): continue
        t = open(p).read()
        for m in re.finditer(r'sectionId:\s*"([^"]+)"', t): vol[m.group(1)] = vol.get(m.group(1),0)+1
        for m in re.finditer(r'\b[qQ]\("[^"]+",\s*"([^"]+)"', t): vol[m.group(1)] = vol.get(m.group(1),0)+1
    return vol

CPL = {  # subjectId -> aspect prefix (tier by syllabus subtopic count)
 "air-law":"A.3","flight-planning":"A.4","aircraft-technical":"A.1","human-performance":"A.6",
 "flight-instruments":"A.7","navigation":"A.9","radio-navigation":"A.10",
}
VOL = {  # subjectId -> bank files (tier by question volume)
 "general-radiotelephony":["gr-questions.ts"],
 "ppl-air-law":["ppl-airlaw-questions.ts","ppl-airlaw-questions-mined.ts"],
 "ir-instruments":["ir-instruments-questions.ts"],
 "ir-special-procedures":["ir-special-procedures-questions.ts"],
 "ir-human-performance":["ir-human-performance-questions.ts"],
 "ir-radio-navigation":["ir-radio-navigation-questions.ts"],
 "ir-air-law-awo":["ir-awo-questions.ts"],
 "ir-flight-performance":["ir-fpp-questions.ts"],
 "ppl-principles-of-flight":["ppl-principles-of-flight-questions.ts"],
}
# PPL/IR subjects that reuse CPL sectionIds -> merge parent map(s).
ALIAS = {
 "ir-meteorology":["meteorology"], "ppl-meteorology":["meteorology"],
 "ppl-navigation":["navigation","flight-instruments"],
 "ppl-flight-planning":["flight-planning"], "ppl-aircraft-technical":["aircraft-technical"],
 "ppl-human-performance":["human-performance"],
}

maps = {"meteorology": MET}
for sid, pfx in CPL.items():  maps[sid] = tier(by_prefix(pfx))
for sid, files in VOL.items(): maps[sid] = tier(volume(files))
for sid, parents in ALIAS.items():
    merged = {}
    for p in parents: merged.update(maps[p])
    maps[sid] = merged

# ── Emit TS ────────────────────────────────────────────────────────────────
def lit(m):
    return "{ " + ", ".join(f'"{c}": {m[c]}' for c in sorted(m)) + " }"
lines = ['''// GENERATED by scripts/gen-exam-priority.py — do not hand-edit (regenerate).
// Cluster-level star ratings per subject aspect. NON-DESTRUCTIVE: these only
// WEIGHT mock-exam sampling (see examSelect.ts); coverage floors keep every
// aspect in every paper. No exam-sitting/recurrence data exists, so ratings use
// a structural proxy — syllabus subtopic count (CPL) or bank volume (IR/GR/PPL)
// — labelled "limited evidence". Meteorology is curated (cross-source overlap).

export type Star = 1 | 2 | 3;
''']
lines.append(f"const MET_STARS: Record<string, Star> = {lit(MET)};\n")
lines.append("const BY_SUBJECT: Record<string, Record<string, Star>> = {")
for sid in sorted(maps):
    key = f'"{sid}"' if re.search(r'[^a-z]', sid) else sid
    val = "MET_STARS" if maps[sid] is MET or sid in ("meteorology","ir-meteorology","ppl-meteorology") else lit(maps[sid])
    if sid in ("ir-meteorology","ppl-meteorology"): val = "MET_STARS"
    if sid == "meteorology": val = "MET_STARS"
    lines.append(f"  {key}: {val},")
lines.append("};\n")
lines.append('''/** Star lookup for a subject, or undefined if unclassified (callers then fall
 *  back to equal sampling — no behaviour change). Unknown sectionIds -> 1 star. */
export function starOfSubject(subjectId: string): ((sectionId: string) => Star) | undefined {
  const map = BY_SUBJECT[subjectId];
  if (!map) return undefined;
  return (sectionId: string) => map[sectionId] ?? 1;
}
''')
open(f"{D}/exam-priority.ts","w").write("\n".join(lines))

# summary
print(f"Classified {len(maps)} subjects:")
for sid in sorted(maps):
    d = {3:0,2:0,1:0}
    for s in maps[sid].values(): d[s]+=1
    print(f"  {sid:26} {len(maps[sid]):2d} aspects  ★★★={d[3]} ★★={d[2]} ★={d[1]}")
